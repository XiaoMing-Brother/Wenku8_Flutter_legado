/// 番茄「分类书库」的官方标签数据。
///
/// 260 个标签分为主分类/主题/角色/情节四组，与榜单分类是两套数据，
/// 不能直接塞进榜单的分类筛选。频道决定每个性别可见的标签范围。
class FanqieLibraryCategory {
  const FanqieLibraryCategory({
    required this.id,
    required this.name,
    required this.group,
  });

  final String id;
  final String name;
  final String group;
}

class FanqieLibraryChannel {
  const FanqieLibraryChannel({
    required this.gender,
    required this.name,
    required this.categoryIds,
  });

  /// 官方接口的 gender 参数：-1 全部、1 男生、0 女生。
  final String gender;
  final String name;
  final Set<String> categoryIds;
}

const fanqieLibraryGroups = ['主分类', '主题', '角色', '情节'];

final List<FanqieLibraryCategory> fanqieLibraryCategories = _categoryRows
    .split('\n')
    .map(_categoryFromRow)
    .whereType<FanqieLibraryCategory>()
    .toList(growable: false);

final List<FanqieLibraryChannel> fanqieLibraryChannels = _channelRows
    .split('\n')
    .map(_channelFromRow)
    .whereType<FanqieLibraryChannel>()
    .toList(growable: false);

FanqieLibraryCategory? _categoryFromRow(String row) {
  final parts = row.split('|');
  if (parts.length != 3) return null;
  return FanqieLibraryCategory(id: parts[0], name: parts[1], group: parts[2]);
}

FanqieLibraryChannel? _channelFromRow(String row) {
  final parts = row.split('|');
  if (parts.length != 3) return null;
  return FanqieLibraryChannel(
    gender: parts[0],
    name: parts[1],
    categoryIds: parts[2].split(',').toSet(),
  );
}

